export function findRecipeBySlug(slug: string) {
  return recipes.find((recipe) => recipe.slug === slug);
}

export type RecipeCategory = {
  name: string;
  recipeCount: number;
};

export function getAllRecipes() {
  return recipes;
}

export function getRecipeBySlug(slug: string) {
  return findRecipeBySlug(slug);
}

export function getCategories(): RecipeCategory[] {
  return Array.from(new Set(recipes.map((recipe) => recipe.category))).map((category) => ({
    name: category,
    recipeCount: recipes.filter((recipe) => recipe.category === category).length
  }));
}

export function getTags() {
  return Array.from(new Set(recipes.flatMap((recipe) => recipe.tags)));
}

export function getFeaturedRecipes(limit = 3) {
  return recipes.slice(0, limit);
}
